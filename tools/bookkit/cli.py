"""Command line of the book builder.

Run from `tools/` (or from anywhere with `uv run --project tools ...`):

    uv run book build                 the whole book (../book) -> ../dist/agentic-sdlc.pdf, and nothing else anywhere
    uv run book build --shots 1,3-5   also save PNG proofs of those pages to <temp>/bookkit/book/pages/
    uv run book build --only 02       build one chapter (quick layout check)
    uv run book build --demo          build the demo of every block (tools/demo) into <temp>/bookkit/demo/
    uv run book watch                 rebuild whenever the chapters or the theme change
    uv run book storyboard mcp        one chapter on one sheet: its opener and every footer, in page order
    uv run book sheet                 proof sheets: every pose and mood, every doodle, every color
    uv run book prompts               every prompt of the book as its own file, ready to copy
    uv run book components            reference of every block and fence, from the registry
    uv run book audit                 build and measure every page: holes, gaps, crooked lines, footers (audit.py)
    uv run book build --content DIR   build any folder with chapters and a book.yml
"""
from __future__ import annotations

import argparse
import contextlib
import fcntl
import hashlib
import re
import shutil
import sys
import tempfile
import time
from pathlib import Path

from .markup import BuildError

ROOT = Path(__file__).resolve().parent.parent     # tools/: the build tool and nothing else
PROJECT = ROOT.parent                             # the repository: tools/, book/, docs/ and dist/
BOOK = PROJECT / "book"                           # the handbook's own text: chapters, book.yml, pictures
DEMO = ROOT / "demo"                              # a chapter showing every block, for checking the layout
DIST = PROJECT / "dist"                           # the built PDF, nothing else
PDF = "agentic-sdlc.pdf"                          # the file name of the book, here and in every release
# The tool's own proofs (page shots, the demo, sheets, exported prompts) live outside the project, in the system's
# temporary folder, which the system empties by itself: nothing built stays in tools/.
LOCAL = Path(tempfile.gettempdir()) / "bookkit"
MARKER = ".bookkit"      # dropped into every folder the tool creates, so it only ever empties its own folders


def fresh_folder(folder: Path) -> None:
    """Empty a folder of generated files - but only if this tool made it."""
    if folder.exists() and not folder.is_dir():
        raise BuildError(f"{folder} is a file, not a folder; choose another --out")
    if folder.exists():
        if not (folder / MARKER).exists() and any(folder.iterdir()):
            raise BuildError(f"{folder} exists and was not created by this tool; move it or choose another --out")
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    (folder / MARKER).write_text("generated by bookkit; safe to delete\n", encoding="utf-8")


def parse_pages(spec: str | None) -> list[int] | None:
    """Turn `"1,3-5"` into `[1, 3, 4, 5]`; `None` or `"all"` means every page."""
    if not spec or spec == "all":
        return None
    pages: list[int] = []
    try:
        for part in spec.split(","):
            first, dash, last = part.partition("-")
            low, high = int(first), int(last if dash else first)
            if not 1 <= low <= high:
                raise ValueError(part)
            pages += range(low, high + 1)
    except ValueError as error:
        raise BuildError(f"cannot read page list {spec!r}; use something like 1,3-5") from error
    return pages


def export_prompts(build, target: Path) -> int:
    """Write every prompt of the book to its own text file, ready to copy.

    Text copied out of a PDF loses indentation and gains line breaks where lines
    wrapped, so the files are the reliable source for readers.
    """
    if not build.prompts:
        if (target / MARKER).exists():
            shutil.rmtree(target)         # a stale export of prompts that no longer exist is misleading
        return 0
    fresh_folder(target)
    index = ["# Prompts", ""]
    for prompt in build.prompts:
        # File names use the chapter's position, which is unique; its number may be absent.
        name = f"{prompt.chapter.index:02d}-{prompt.order:02d}.md"
        (target / name).write_text(prompt.text, encoding="utf-8")
        label = f"{prompt.chapter.number}.{prompt.order} " if prompt.chapter.number else ""
        index.append(f"- [{label}{prompt.title or prompt.chapter.title}]({name})")
    (target / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    return len(build.prompts)


def proofs_folder(out: Path) -> Path:
    """Where the page proofs go.

    `dist/` holds only PDFs, so for a PDF inside it they go to `<temp>/bookkit/<name>/`; for a PDF anywhere else,
    next to it.
    """
    try:
        relative = out.resolve().parent.relative_to(DIST.resolve())
    except ValueError:
        return out.parent
    return LOCAL / (relative.as_posix().replace("/", "-") if relative.parts else "book")


@contextlib.contextmanager
def exclusive(out: Path):
    """One build at a time per output: a second one waits for the first instead of both writing the same PDF and
    emptying each other's proof folders."""
    LOCAL.mkdir(parents=True, exist_ok=True)
    key = hashlib.sha1(str(out.resolve()).encode()).hexdigest()[:12]
    with open(LOCAL / f"build-{key}.lock", "w") as handle:
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            print(f"waiting for another build of {out} to finish...", flush=True)
            fcntl.flock(handle, fcntl.LOCK_EX)
        yield


def build(args) -> int:
    from .compiler import build_html
    from .render import render_isolated

    out = Path(args.out)
    pages = parse_pages(args.shots)       # a bad page list must fail before anything is deleted
    started = time.time()
    result = build_html(Path(args.content), only=args.only)
    with exclusive(out):
        out.parent.mkdir(parents=True, exist_ok=True)   # only once there is something to put there
        shots_dir = proofs_folder(out) / "pages" if args.shots else None
        if shots_dir:
            fresh_folder(shots_dir)           # stale proofs of pages that no longer exist are misleading
        with tempfile.TemporaryDirectory(prefix="bookkit-") as work:   # the laid-out page, gone after the build
            source = Path(work) / "book.html"
            source.write_text(result.html, encoding="utf-8")
            report = render_isolated(source, None if args.no_pdf else out, shots_dir, pages, scale=args.scale,
                                     vocabulary=result.config.vocabulary())
    if pages and report["pages"] < max(pages):
        report["warnings"].append(f"--shots asks for page {max(pages)}, but the book has {report['pages']}")
    for warning in report["warnings"]:
        print(f"  warning: {warning}")
    where = "" if args.no_pdf else f" -> {out}"
    print(f"ok: {report['pages']} pages{where} ({time.time() - started:.1f} s)")
    if report.get("layout"):
        print(f"  layout {report['layout']['fingerprint']} in {report.get('browser')}")
    for shot in report["shots"]:
        print(f"  {shot}")
    return 1 if report["warnings"] and args.strict else 0


def storyboard(args) -> int:
    """One chapter on one sheet: its opener and every footer in page order, to judge the chapter's story and its
    world before looking at the pages."""
    from . import design
    from .compiler import build_html
    from .render import render_isolated, screenshot_html

    result = build_html(Path(args.content), only=args.only, world=args.world)
    out = LOCAL / "storyboard"
    name = re.sub(r"[^0-9A-Za-z_-]+", "_", args.only + (f"-{args.world}" if args.world else "")) or "book"
    frames, sheet_path = out / f"{name}-frames", out / f"{name}.png"
    with exclusive(sheet_path):
        fresh_folder(frames)
        with tempfile.TemporaryDirectory(prefix="bookkit-") as work:
            source = Path(work) / "book.html"
            source.write_text(result.html, encoding="utf-8")
            report = render_isolated(source, None, None, None, scale=args.scale, frames_dir=frames,
                                     vocabulary=result.config.vocabulary())
        for warning in report["warnings"]:
            print(f"  warning: {warning}")
        shots = report.get("frames") or []
        opener = "".join(f'<img class="opener" src="{Path(f["path"]).as_uri()}">' for f in shots if f["opener"])
        cells = "".join(f'<figure><img src="{Path(f["path"]).as_uri()}"><figcaption>{f["page"]}</figcaption>'
                        f'</figure>' for f in shots if not f["opener"])
        sheet = (f"<html><body style='margin:0;padding:16px;background:{design.DESK};font:600 14px sans-serif;"
                 f"display:flex;gap:16px;align-items:flex-start'><div style='width:420px;flex:none'>{opener}</div>"
                 f"<div style='display:grid;grid-template-columns:repeat(2,560px);gap:10px'>{cells}</div>"
                 f"<style>img{{width:100%;display:block;border:1px solid {design.INK}}} figure{{margin:0}}"
                 f"figcaption{{padding:2px 0}}</style></body></html>")
        target = screenshot_html(sheet, sheet_path, width=1640, height=900)
    print(f"ok: {len(shots)} frames -> {target}")
    return 1 if report["warnings"] and args.strict else 0


def watch(args) -> int:
    """Rebuild in a fresh interpreter on every change, so edited modules are always picked up."""
    import subprocess

    def stamp() -> float:
        latest = 0.0
        for file in [*Path(args.content).rglob("*"), *(ROOT / "bookkit").rglob("*")]:
            if "__pycache__" not in file.parts:
                with contextlib.suppress(OSError):     # a file saved or deleted while we look
                    latest = max(latest, file.stat().st_mtime) if file.is_file() else latest
        return latest

    command = [sys.executable, "-m", "bookkit.cli", "build", "--content", args.content, "--out", args.out,
               "--scale", str(args.scale)]
    for flag, value in (("--only", args.only), ("--shots", args.shots)):
        if value:
            command += [flag, value]
    for flag, on in (("--no-pdf", args.no_pdf), ("--strict", args.strict)):
        if on:
            command.append(flag)
    print(f"watching {args.content} and {ROOT / 'bookkit'} - press Ctrl+C to stop", flush=True)
    last = 0.0
    try:
        while True:
            current = stamp()
            if current != last:
                last = current
                subprocess.run(command, cwd=ROOT, check=False)
            time.sleep(0.7)
    except KeyboardInterrupt:
        return 0


def sheet(args) -> int:
    """Render the proof sheets: characters, doodles and the palette."""
    from . import proofs
    from .config import load_config

    out = Path(args.out)
    for path in (proofs.character_sheet(load_config(Path(args.content)), out / "characters.png"),
                 proofs.doodle_sheet(out / "doodles.png"), proofs.palette_sheet(out / "palette.png")):
        print(f"ok: {path}")
    return 0


def prompts(args) -> int:
    """Write every prompt of the book to its own file."""
    from .compiler import build_html

    out = Path(args.out)
    count = export_prompts(build_html(Path(args.content)), out)
    print(f"ok: {count} prompts -> {out}")
    return 0


def components(args) -> int:
    """Print the component reference generated from the registry."""
    from .components import reference

    print(reference())
    return 0


def audit(args) -> int:
    """Build the book once and measure every page; fail on an error or on a warning the baseline does not accept."""
    import json

    from . import audit as auditing

    content = Path(args.content).resolve()
    baseline = Path(args.baseline).resolve() if args.baseline else None
    if args.write_baseline and not baseline:
        raise BuildError("--write-baseline needs --baseline FILE: the file to write")
    sheets = Path(args.sheets).resolve() if args.sheets else None
    pdf = Path(args.pdf).resolve() if args.pdf else None
    with exclusive(pdf or LOCAL / "audit" / "audit.lock"):
        if sheets:
            sheets.mkdir(parents=True, exist_ok=True)
        result = auditing.run(content, only=args.only, baseline=None if args.write_baseline else baseline,
                              base=args.base, sheets=sheets, pdf=pdf)
    if args.write_baseline:
        count = auditing.write_baseline(baseline, result["findings"], auditing.load_baseline(baseline, strict=False))
        print(f"ok: {count} warning(s) -> {baseline}; give each new entry its reason")
    print(auditing.summary(result))
    if args.json:
        Path(args.json).parent.mkdir(parents=True, exist_ok=True)
        Path(args.json).write_text(json.dumps(result, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"  -> {args.json}")
    if args.md:
        Path(args.md).parent.mkdir(parents=True, exist_ok=True)
        Path(args.md).write_text(auditing.markdown(result), encoding="utf-8")
        print(f"  -> {args.md}")
    for sheet in result["sheets"]:
        print(f"  {sheet['path']}")
    if args.advisory and not auditing.failed(result["findings"], warnings=False):
        return 0                          # the layout warnings are the maintainer's (tools/layout_gate.py)
    return 1 if auditing.failed(result["findings"]) and not args.write_baseline else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="book", description="Build the book from Markdown to an A4 PDF.")
    commands = parser.add_subparsers(dest="command", required=True)
    for name, handler, summary in (("build", build, "build the PDF"), ("watch", watch, "rebuild on change")):
        sub = commands.add_parser(name, help=summary)
        sub.add_argument("--content", help=f"folder with chapters and book.yml (default: {BOOK})")
        sub.add_argument("--out", help=f"path of the PDF to write (default: {DIST / PDF})")
        sub.add_argument("--demo", action="store_true", help="build the demo of every block instead of the book")
        sub.add_argument("--only", help="build only chapters whose file name contains this text")
        sub.add_argument("--shots", help="save PNG proofs of pages: all | 1,3-5")
        sub.add_argument("--scale", type=float, default=1.0, help="PNG pixel density (2 for sharper proofs)")
        sub.add_argument("--no-pdf", action="store_true", help="skip writing the PDF")
        sub.add_argument("--strict", action="store_true", help="exit with an error if the layout has warnings")
        sub.set_defaults(handler=handler)
    sub = commands.add_parser("storyboard", help="one chapter on one sheet: its opener and every footer in order")
    sub.add_argument("only", help="the chapter, as for --only")
    sub.add_argument("--world", help="preview the chapter in this world, without changing its file")
    sub.add_argument("--content", default=str(BOOK))
    sub.add_argument("--scale", type=float, default=1.0)
    sub.add_argument("--strict", action="store_true", help="exit with an error if the layout has warnings")
    sub.set_defaults(handler=storyboard)
    sub = commands.add_parser("sheet", help="render proof sheets: characters, doodles, palette")
    sub.add_argument("--content", default=str(BOOK))
    sub.add_argument("--out", default=str(LOCAL / "sheets"), help="folder for the PNG files")
    sub.set_defaults(handler=sheet)
    sub = commands.add_parser("prompts", help="write every prompt of the book to its own file")
    sub.add_argument("--content", default=str(BOOK))
    sub.add_argument("--out", default=str(LOCAL / "prompts"), help="folder for the prompt files")
    sub.set_defaults(handler=prompts)
    sub = commands.add_parser("components", help="print the reference of blocks and fences")
    sub.set_defaults(handler=components)
    sub = commands.add_parser("audit", help="build and measure every page; fail on new findings")
    sub.add_argument("--content", default=str(BOOK))
    sub.add_argument("--only", help="audit only chapters whose file name contains this text")
    sub.add_argument("--json", help="write every finding to this JSON file")
    sub.add_argument("--md", help="write the report to this Markdown file")
    sub.add_argument("--sheets", help="folder for contact sheets of the flagged pages")
    sub.add_argument("--baseline", help="JSON of accepted findings, each with its reason")
    sub.add_argument("--write-baseline", action="store_true", help="write every warning found into --baseline")
    sub.add_argument("--base", help="git ref to compare book/ with: a change needs a new version (e.g. origin/main)")
    sub.add_argument("--pdf", help="also print the PDF here")
    sub.add_argument("--advisory", action="store_true",
                     help="report layout warnings but fail only on errors (a contributor's pull request)")
    sub.set_defaults(handler=audit)
    args = parser.parse_args(argv)
    try:
        if args.command in ("build", "watch"):
            if args.demo and (args.content or args.out):
                raise BuildError("--demo has its own content and output; drop --content and --out")
            content, out = (DEMO, LOCAL / "demo" / "book.pdf") if args.demo else (BOOK, DIST / PDF)
            # Absolute paths: `watch` rebuilds in a child process whose working directory differs.
            args.content = str(Path(args.content or content).resolve())
            args.out = str(Path(args.out or out).resolve())
        return args.handler(args)
    except BuildError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
